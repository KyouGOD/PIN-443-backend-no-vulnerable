API_DESCRIPTION = """
Банковское приложение API с OAuth2 аутентификацией.

## Аутентификация
API поддерживает аутентификацию через:
* Google OAuth2
* Yandex OAuth2

После успешной аутентификации вы получите JWT токен, который необходимо использовать
для всех последующих запросов в заголовке Authorization:
`Authorization: Bearer ваш_jwt_токен`

## Возможности
* Создание и управление банковскими счетами (текущий, дебетовый, кредитный)
* Внесение и снятие средств
* Переводы между счетами
* Просмотр истории транзакций

## Ограничения
* Максимальная сумма снятия/перевода за одну операцию: 30 000
* Операции с дебетовым счетом блокируются, если у пользователя есть кредитный счет с балансом менее -20 000
* При пополнении текущего счета на сумму более 1 000 000 автоматически начисляется +2000 на дебетовый счет пользователя
"""

